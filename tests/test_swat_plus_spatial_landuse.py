import io,json,zipfile
from pathlib import Path
import pytest
from ecodata.round1 import convert
from ecodata.core.exceptions import SchemaError
BASE=Path(__file__).parents[1]/'examples/ai_round1/swat_plus/spatial_landuse'

def case(label='standard'):
    return (BASE/f'A_synthetic_{label}.zip').read_bytes(),json.loads((BASE/f'config_{label}.json').read_text(encoding='utf8'))

def change(data,filename,transform):
    result=io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(data)) as z,zipfile.ZipFile(result,'w') as out:
        for name in z.namelist():
            b=z.read(name)
            if name==filename:b=transform(b)
            out.writestr(name,b)
    return result.getvalue()

@pytest.mark.parametrize('label,n',[('standard',2),('mapped',3)])
def test_independent_attribute_rows_and_analytic_geometry(label,n):
    data,cfg=case(label);files,report=convert('swat_plus',data,cfg)
    # Independent native token parsing: existing official attributes + hand
    # rectangle geometry, not expected values generated by converter.
    actual=[r.split() for r in files['hru-data.hru'].decode('ascii').splitlines()[2:]]
    reference=[r.split() for r in (BASE/f'format_reference_{label}.hru').read_text().splitlines()[2:]]
    assert actual==reference and len(actual)==n
    association=json.loads(files['landuse_HRU_association.json'])
    assert sorted((r['hru_id'],r['area_m2'],r['uncovered_m2']) for r in association)==[(str(i),5000.,0.) for i in range(1,n+1)]
    assert 'file.cio' not in files and report['interpolation']=='none'
    assert report['coordinate_unit']=='m' and report['time_axis']=='static'

@pytest.mark.parametrize('problem,match',[
 ('gap','覆盖缺口'),('mixed','混合地类'),('overlap','土地利用面重叠'),('hru_overlap','HRU.*重叠'),
 ('missing_id','缺属性'),('identity','身份不一致'),('invalid','有效非空面'),('nan','有限二维|有效非空'),('z','二维'),('crs','CRS与配置冲突')])
def test_geometry_errors_are_not_filled_or_guessed(problem,match):
    data,cfg=case()
    name='HRU.geojson' if problem in {'hru_overlap','missing_id','identity'} else 'land.geojson'
    def mutate(b):
        obj=json.loads(b);f=obj['features']
        if problem=='gap':f.pop(0)
        elif problem=='mixed':f[0]['properties']['code']='M'
        elif problem=='overlap':f.append(f[0])
        elif problem=='hru_overlap':f[1]['geometry']=f[0]['geometry']
        elif problem=='missing_id':f[0]['properties']={}
        elif problem=='identity':f[0]['properties']['id']=99
        elif problem=='invalid':f[0]['geometry']['coordinates']=[[[0,0],[1,1],[1,0],[0,1],[0,0]]]
        elif problem=='nan':f[0]['geometry']['coordinates'][0][0][0]=float('nan')
        elif problem=='z':f[0]['geometry']['coordinates']=[[[*p,1] for p in f[0]['geometry']['coordinates'][0]]]
        elif problem=='crs':obj['crs']={'type':'name','properties':{'name':'EPSG:32632'}}
        return json.dumps(obj).encode()
    with pytest.raises(SchemaError,match=match):convert('swat_plus',change(data,name,mutate),cfg)

@pytest.mark.parametrize('key,value,match',[
 ('source_crs','EPSG:4326','米制投影'),('coordinate_unit','km','coordinate_unit'),
 ('spatial_policy','majority','不取多数'),('category_mapping',{'C':'cosy_lum'},'缺category_mapping'),
 ('category_mapping',{'C':'missing_lum','M':'mntill_corn_lum'},'引用名称不存在'),
 ('fields',{'id':'id'},'所有字段'),('references',{},'引用数据库'),('target_model_version','61','62.0.0')])
def test_mapping_units_references_missing_columns(key,value,match):
    data,cfg=case();cfg[key]=value
    with pytest.raises(SchemaError,match=match):convert('swat_plus',data,cfg)

def test_missing_source_column():
    data,cfg=case();cfg['fields']['soil']='nonexistent'
    with pytest.raises(SchemaError,match='缺列'):convert('swat_plus',data,cfg)

def test_static_input_has_no_missing_timestamp_to_fill():
    # Unlike daily weather, this target has no date field. Geometry association
    # cannot alter time; all source parameter names are retained token for token.
    data,cfg=case();files,r=convert('swat_plus',data,cfg)
    assert r['time_axis']=='static' and b'date' not in files['hru-data.hru']
